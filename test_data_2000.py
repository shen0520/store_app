# ===== 条码生成 =====
def gen_ean13(prefix):
    """生成 EAN-13 条码（含正确校验位）"""
    body = str(prefix)[:12].zfill(12)
    # 计算校验位
    odd = sum(int(body[i]) for i in range(0, 12, 2))
    even = sum(int(body[i]) for i in range(1, 12, 2))
    total = odd + even * 3
    check = (10 - (total % 10)) % 10
    return body + str(check)

# 条码前缀池（中国商品条码前缀 690-699）
used_barcodes = set()

def get_unique_barcode():
    while True:
        # 69x + 随机8位 = 12位，加校验位=13位
        prefix = random.choice([690, 691, 692, 693, 694, 695, 696, 697, 698, 699])
        suffix = random.randint(10000000, 99999999)
        full = str(prefix) + str(suffix)
        barcode = gen_ean13(full)
        if barcode not in used_barcodes:
            used_barcodes.add(barcode)
            return barcode

# ===== 价格生成 =====
def gen_price(base_low, base_high, is_drink=False):
    """生成合理价格"""
    base = random.uniform(base_low, base_high)
    # 常见定价策略：x.5, x.8, x.9, x.99
    endings = [0.5, 0.8, 0.9, 0.99, 0.00, 0.00]
    end = random.choice(endings)
    price = int(base) + end
    if price < 0.5:
        price = 0.5
    return round(price, 2)

